addpath(fullfile(fileparts(mfilename('fullpath')), '..'));
P = halfcar.params.load();
road = halfcar.road.bumps([20 0.06 2.0]);
speeds = 6 * ones(700, 1);
out = halfcar.sim.simulate(P, road, speeds);
k = find(out.s >= 21, 1);
fig = figure('Color', 'w', 'Position', [100 100 1200 520]);
hud = render.scene.hud_create(fig, [0.06 0.90 0.88 0.07]);
ax = axes('Parent', fig, 'Position', [0.06 0.04 0.88 0.82]);
render.scene.draw_frame(ax, P, road, out, k);
render.scene.hud_update(hud, out.t(k), out.s(k), out.v(k), out.z_B(k), out.phi(k));
print(fig, 'frame.png', '-dpng', '-r150');
