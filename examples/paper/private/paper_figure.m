function fig = paper_figure(width_cm, height_cm)
fig = figure('Units', 'centimeters', 'Position', [2 2 width_cm height_cm], 'Color', 'w', ...
    'InvertHardcopy', 'off', 'PaperPositionMode', 'auto');
try
    theme(fig, 'light');
catch
end
set(fig, 'DefaultAxesFontName', 'Times New Roman', 'DefaultAxesFontSize', 9, ...
    'DefaultTextFontName', 'Times New Roman', 'DefaultLegendFontName', 'Times New Roman', ...
    'DefaultAxesColor', 'w', 'DefaultAxesBox', 'off', 'DefaultAxesTickDir', 'out', ...
    'DefaultAxesXGrid', 'on', 'DefaultAxesYGrid', 'on', 'DefaultAxesGridAlpha', 0.15, ...
    'DefaultAxesXColor', [0.1 0.1 0.1], 'DefaultAxesYColor', [0.1 0.1 0.1], 'DefaultLineLineWidth', 1.1);
end
