function fig = white_figure(width_cm, height_cm)
%WHITE_FIGURE A figure with a white background and dark text whatever the system theme.
fig = figure('Units', 'centimeters', 'Position', [2 2 width_cm height_cm], 'Color', 'w', ...
    'InvertHardcopy', 'off', 'PaperPositionMode', 'auto');
try
    theme(fig, 'light');
catch
end
ink = [0.1 0.1 0.1];
set(fig, 'Color', 'w', 'DefaultAxesColor', 'w', 'DefaultAxesXColor', ink, 'DefaultAxesYColor', ink, ...
    'DefaultAxesGridColor', [0.15 0.15 0.15], 'DefaultAxesGridAlpha', 0.15, 'DefaultAxesFontName', 'Times New Roman', ...
    'DefaultAxesFontSize', 9, 'DefaultTextFontName', 'Times New Roman', 'DefaultTextColor', ink, ...
    'DefaultLegendFontName', 'Times New Roman', 'DefaultLegendTextColor', ink, 'DefaultLegendColor', 'w', ...
    'DefaultAxesBox', 'off', 'DefaultAxesTickDir', 'out', 'DefaultAxesXGrid', 'on', 'DefaultAxesYGrid', 'on', ...
    'DefaultLineLineWidth', 1.0, 'DefaultAxesTitleFontWeight', 'normal');
end
