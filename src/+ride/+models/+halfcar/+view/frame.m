function frame(ax, P, road, out, k)
g = ride.models.halfcar.view.geometry();
c = ride.render.scene.colors();
L = P.L;
ys = g.y_scale;
s = out.s(k);
x_front = 0;
x_rear = -L;
z_B = out.z_B(k);
phi = out.phi(k);
z_Bf = z_B - P.body.l_f * phi;
z_Br = z_B + P.body.l_r * phi;
z_Wf = out.z_Wf(k);
z_Wr = out.z_Wr(k);
zeta_f = ride.core.terrain.height(road, s);
zeta_r = ride.core.terrain.height(road, s - L);
ride.render.scene.draw_background(ax, g, c, road, s, (x_front + x_rear) / 2);
y_road_f = g.ground_y + zeta_f * ys;
y_road_r = g.ground_y + zeta_r * ys;
y_Wf = y_road_f + g.wheel_ry + min(z_Wf - zeta_f, 0) * ys;
y_Wr = y_road_r + g.wheel_ry + min(z_Wr - zeta_r, 0) * ys;
y_gap = g.y_b_nom - g.y_w_nom;
y_Bf = y_Wf + y_gap + (z_Bf - z_Wf) * ys;
y_Br = y_Wr + y_gap + (z_Br - z_Wr) * ys;
rot = s / g.wheel_r;
on_f = any(road.bumps(:, 1) <= s & s <= road.bumps(:, 1) + road.bumps(:, 3)) || abs(zeta_f) > g.obstacle_flag_m;
on_r = any(road.bumps(:, 1) <= s - L & s - L <= road.bumps(:, 1) + road.bumps(:, 3)) || abs(zeta_r) > g.obstacle_flag_m;
ride.render.scene.draw_wheel(ax, x_front, y_Wf, y_road_f, y_Bf, on_f, rot, g, c);
ride.render.scene.draw_wheel(ax, x_rear, y_Wr, y_road_r, y_Br, on_r, rot, g, c);
o = g.mb_overhang;
slope = (y_Bf - y_Br) / (x_front - x_rear);
fx = x_front + o;
fy = y_Bf + slope * o;
rx = x_rear - o;
ry = y_Br - slope * o;
hh = g.h_mb / 2;
fill(ax, [rx fx fx rx], [ry - hh, fy - hh, fy + hh, ry + hh], ride.render.scene.rgb(c.body), 'EdgeColor', [0.2 0.2 0.2], 'LineWidth', 1.2);
plot(ax, (x_front + x_rear) / 2, (y_Bf + y_Br) / 2, 'o', 'MarkerFaceColor', 'w', 'MarkerEdgeColor', 'w', 'MarkerSize', 3);
hold(ax, 'off');
end
